"""Assign every KB ticket to fit / calib / val (80/10/10), stratified on type|priority.

Outputs:
  data/processed/kb_partitions.parquet  ticket_id, partition
  reports/kb_partitions_summary.md      counts, label shares per partition, SHA-256 of the parquet

The classifier fits on `fit`, probability calibrators on `calib`, thresholds on `val`.
"""
import hashlib
from pathlib import Path

import pandas as pd
from sklearn.model_selection import train_test_split

ROOT = Path(__file__).resolve().parents[1]
KB = ROOT / "data" / "processed" / "kb_train.parquet"
TEST_INPUTS = ROOT / "data" / "processed" / "test_inputs.parquet"
OUT = ROOT / "data" / "processed" / "kb_partitions.parquet"
SUMMARY = ROOT / "reports" / "kb_partitions_summary.md"
SEED = 42
PARTITIONS = ["fit", "calib", "val"]
SHARE_COLS = ["type", "priority", "queue", "language"]


def split(kb: pd.DataFrame) -> pd.DataFrame:
    strata = kb["type"] + "|" + kb["priority"]
    fit_ids, rest_ids, _, rest_strata = train_test_split(
        kb["ticket_id"], strata, test_size=0.2, stratify=strata, random_state=SEED
    )
    calib_ids, val_ids = train_test_split(
        rest_ids, test_size=0.5, stratify=rest_strata, random_state=SEED
    )
    parts = pd.concat(
        [
            pd.DataFrame({"ticket_id": ids.to_numpy(), "partition": name})
            for name, ids in zip(PARTITIONS, [fit_ids, calib_ids, val_ids])
        ]
    )
    return parts.sort_values("ticket_id").reset_index(drop=True)


def check(parts: pd.DataFrame, kb_ids: set[str], test_ids: set[str]) -> None:
    groups = {p: set(parts.loc[parts["partition"] == p, "ticket_id"]) for p in PARTITIONS}
    for i, a in enumerate(PARTITIONS):
        for b in PARTITIONS[i + 1 :]:
            if groups[a] & groups[b]:
                raise RuntimeError(f"partitions {a} and {b} overlap")
    if not parts["ticket_id"].is_unique:
        raise RuntimeError("duplicate ticket_id in partitions")
    if set(parts["ticket_id"]) != kb_ids:
        raise RuntimeError("partition union does not equal KB ticket_ids")
    leaked = set(parts["ticket_id"]) & test_ids
    if leaked:
        raise RuntimeError(f"{len(leaked)} holdout ticket_ids found in partitions")


def share_table(df: pd.DataFrame, col: str) -> tuple[str, float]:
    shares = pd.crosstab(df[col], df["partition"], normalize="columns")[PARTITIONS]
    shares = shares.loc[sorted(shares.index)]
    max_diff = float((shares.max(axis=1) - shares.min(axis=1)).max())
    lines = [f"| {col} | " + " | ".join(PARTITIONS) + " |", "|---|" + "---:|" * len(PARTITIONS)]
    for value, row in shares.iterrows():
        lines.append(f"| {value} | " + " | ".join(f"{v:.4f}" for v in row) + " |")
    return "\n".join(lines), max_diff


def write_summary(parts: pd.DataFrame, kb: pd.DataFrame, sha: str) -> dict[str, float]:
    df = parts.merge(kb[["ticket_id", *SHARE_COLS]], on="ticket_id", validate="one_to_one")
    counts = parts["partition"].value_counts()
    total = len(parts)

    out = [
        "# KB partitions",
        "",
        f"Generated by `scripts/make_partitions.py` (seed {SEED}). "
        "Stratified on `type|priority` (12 strata), 80/10/10.",
        "",
        f"`data/processed/kb_partitions.parquet` SHA-256: `{sha}`",
        "",
        "## Row counts",
        "",
        "| partition | rows | share |",
        "|---|---:|---:|",
    ]
    for p in PARTITIONS:
        out.append(f"| {p} | {counts[p]} | {counts[p] / total:.4f} |")
    out.append(f"| total | {total} | 1.0000 |")

    max_diffs = {}
    for col in SHARE_COLS:
        table, max_diffs[col] = share_table(df, col)
        out += ["", f"## {col}", "", table, "", f"Max share difference between partitions: {max_diffs[col]:.4f}"]

    SUMMARY.parent.mkdir(parents=True, exist_ok=True)
    SUMMARY.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    return max_diffs


def main() -> None:
    kb = pd.read_parquet(KB).sort_values("ticket_id").reset_index(drop=True)
    test_ids = set(pd.read_parquet(TEST_INPUTS, columns=["ticket_id"])["ticket_id"])

    parts = split(kb)
    check(parts, set(kb["ticket_id"]), test_ids)

    OUT.parent.mkdir(parents=True, exist_ok=True)
    parts.to_parquet(OUT, index=False)
    sha = hashlib.sha256(OUT.read_bytes()).hexdigest()
    max_diffs = write_summary(parts, kb, sha)

    print(parts["partition"].value_counts().reindex(PARTITIONS).to_dict())
    print({k: round(v, 4) for k, v in max_diffs.items()})
    print(f"sha256={sha}")


if __name__ == "__main__":
    main()
