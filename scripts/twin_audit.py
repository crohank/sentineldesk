"""Flag holdout tickets that paraphrase a KB ticket (word TF-IDF cosine >= threshold).

Complements dup_audit.py: 5-gram Jaccard there only catches near-copies (12 tickets),
while the generator's paraphrases swap a word every few words and slip past it.
Reads kb_train and test_inputs only. Writes reports/twin_holdout_ids.txt and
reports/twin_audit.md.
"""
import argparse
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.feature_extraction.text import TfidfVectorizer

ROOT = Path(__file__).resolve().parents[1]
PROC = ROOT / "data" / "processed"
REPORTS = ROOT / "reports"
CHUNK = 1000


def max_kb_similarity(kb_body: pd.Series, test_body: pd.Series) -> tuple[np.ndarray, np.ndarray]:
    # Same word features as baseline_tfidf.py, which reproduces the 520 / 92 counts in D1-14.
    vec = TfidfVectorizer(ngram_range=(1, 2), min_df=2, sublinear_tf=True)
    kb_m = vec.fit_transform(kb_body)
    te_m = vec.transform(test_body)
    best = np.zeros(te_m.shape[0])
    arg = np.zeros(te_m.shape[0], dtype=int)
    for start in range(0, te_m.shape[0], CHUNK):
        sims = (te_m[start:start + CHUNK] @ kb_m.T).toarray()
        arg[start:start + CHUNK] = sims.argmax(axis=1)
        best[start:start + CHUNK] = sims.max(axis=1)
    return best, arg


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--threshold", type=float, default=0.8)
    threshold = ap.parse_args().threshold

    kb = pd.read_parquet(PROC / "kb_train.parquet", columns=["ticket_id", "subject", "body"])
    te = pd.read_parquet(PROC / "test_inputs.parquet", columns=["ticket_id", "subject", "body"])
    best, arg = max_kb_similarity(kb["subject"] + " \n " + kb["body"], te["subject"] + " \n " + te["body"])
    te = te.assign(sim=best, kb_id=kb["ticket_id"].to_numpy()[arg], kb_body=kb["body"].to_numpy()[arg])

    flagged = te[te.sim >= threshold].sort_values("ticket_id")
    REPORTS.mkdir(exist_ok=True)
    (REPORTS / "twin_holdout_ids.txt").write_text(
        "".join(f"{t}\n" for t in flagged.ticket_id), encoding="utf-8", newline="\n")

    bands = [0.7, 0.8, 0.85, 0.9, 0.95]
    lines = [
        "# Paraphrase-twin audit",
        "",
        "Generated by `scripts/twin_audit.py`. Inputs: `kb_train.parquet`, `test_inputs.parquet`. "
        "`test_labels.parquet` is not read.",
        "",
        "Method: word 1-2 gram TF-IDF (min_df=2, sublinear tf) over subject + body, fit on the KB; "
        "for each holdout ticket, the highest cosine similarity to any KB ticket.",
        "",
        f"Threshold: {threshold}. Flagged holdout tickets: **{len(flagged)}** of {len(te)} "
        f"({len(flagged) / len(te) * 100:.1f}%). IDs in `twin_holdout_ids.txt`.",
        "",
        "Compare `near_dup_audit.md` (MinHash 5-gram Jaccard >= 0.85), which catches near-copies only.",
        "",
        "| max cosine >= | holdout tickets |",
        "|---|---|",
        *[f"| {b} | {(te.sim >= b).sum()} |" for b in bands],
        "",
        "## Examples near the threshold",
        "",
    ]
    for _, r in flagged.sort_values("sim").head(3).iterrows():
        lines += [f"**{r.ticket_id}** vs **{r.kb_id}** (cosine {r.sim:.3f})", "",
                  f"- holdout: {r.body[:200].replace(chr(10), ' ')}",
                  f"- KB: {r.kb_body[:200].replace(chr(10), ' ')}", ""]
    (REPORTS / "twin_audit.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")

    for b in bands:
        print(f"cosine >= {b}: {(te.sim >= b).sum()}")
    print(f"flagged {len(flagged)} at >= {threshold}, wrote reports/twin_holdout_ids.txt")


if __name__ == "__main__":
    main()
