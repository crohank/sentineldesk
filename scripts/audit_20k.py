"""Measure whether the older 20k CSV can safely add KB rows.

Reads data/raw/dataset-tickets-multi-lang-4-20k.csv, kb_train and test_inputs (never test_labels).
Cleans the 20k file with the make_split.py rules, then sorts each row into:
  matches a KB body, matches a holdout body, repeated inside the 20k file, or new.
New rows get IDs EXT-00000.. and a holdout_twin flag (word 1-2 gram TF-IDF cosine >= 0.8 to
any holdout ticket, the twin_audit.py rule). Writes data/processed/extra_20k.parquet and
reports/audit_20k.md.
"""
import hashlib
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.feature_extraction.text import TfidfVectorizer

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw" / "dataset-tickets-multi-lang-4-20k.csv"
PROC = ROOT / "data" / "processed"
REPORT = ROOT / "reports" / "audit_20k.md"
LABELS = ["type", "queue", "priority", "language"]
TWIN = 0.8


def key(s: pd.Series) -> pd.Series:
    return s.str.strip().str.lower()


def clean(df: pd.DataFrame) -> pd.DataFrame:
    df = df.copy()
    for c in ["subject", "body", "answer"]:
        df[c] = df[c].fillna("").str.replace("\\n", "\n", regex=False)
    return df


def max_cosine(fit_text: pd.Series, a: pd.Series, b: pd.Series) -> np.ndarray:
    vec = TfidfVectorizer(ngram_range=(1, 2), min_df=2, sublinear_tf=True).fit(fit_text)
    A, B = vec.transform(a), vec.transform(b)
    return np.concatenate([(A[s:s + 1000] @ B.T).max(axis=1).toarray().ravel()
                           for s in range(0, A.shape[0], 1000)])


def main() -> None:
    sha = hashlib.sha256(RAW.read_bytes()).hexdigest()
    raw = pd.read_csv(RAW)
    x = clean(raw)
    x = x[x["body"].str.strip() != ""]
    n_empty = len(raw) - len(x)
    kb = pd.read_parquet(PROC / "kb_train.parquet")
    te = pd.read_parquet(PROC / "test_inputs.parquet")

    x["k"] = key(x["body"])
    kb_keys, te_keys = set(key(kb["body"])), set(key(te["body"]))
    in_kb, in_te = x["k"].isin(kb_keys), x["k"].isin(te_keys)

    ov = x[in_kb].merge(kb.assign(k=key(kb["body"]))[["k", *LABELS]], on="k", suffixes=("", "_kb"))
    agree = {c: (ov[c] == ov[c + "_kb"]).mean() for c in LABELS}

    rest = x[~in_kb & ~in_te]
    new = rest.drop_duplicates("k", keep="first").reset_index(drop=True)
    n_repeat = len(rest) - len(new)
    new["ticket_id"] = [f"EXT-{i:05d}" for i in range(len(new))]

    ticket = lambda d: d["subject"] + " \n " + d["body"]
    fit_text = pd.concat([ticket(kb), ticket(new)])
    new["holdout_sim"] = max_cosine(fit_text, ticket(new), ticket(te))
    new["holdout_twin"] = new["holdout_sim"] >= TWIN
    new["kb_sim"] = max_cosine(fit_text, ticket(new), ticket(kb))

    unknown = {c: sorted(set(new[c]) - set(kb[c])) for c in ["type", "queue", "priority"]}
    cols = ["ticket_id", "subject", "body", "answer", *LABELS,
            *[c for c in new.columns if c.startswith("tag_")], "holdout_sim", "holdout_twin", "kb_sim"]
    new[cols].to_parquet(PROC / "extra_20k.parquet", index=False)

    share = lambda d, c: (d[c].value_counts(normalize=True) * 100).round(1)
    dist = pd.concat({"kb %": share(kb, "queue"), "new 20k %": share(new, "queue")}, axis=1).fillna(0)
    L = [
        "# 20k file audit",
        "",
        "Generated by `scripts/audit_20k.py`. Reads the 20k CSV, `kb_train` and `test_inputs`; never `test_labels`.",
        "",
        f"Source `{RAW.name}`, SHA-256 `{sha}`.",
        "",
        "| rows | count |",
        "|---|---|",
        f"| raw | {len(raw)} |",
        f"| empty body, dropped | {n_empty} |",
        f"| body matches a KB ticket | {int(in_kb.sum())} |",
        f"| body matches a holdout ticket (must never enter the KB) | {int(in_te.sum())} |",
        f"| repeated inside the 20k file | {n_repeat} |",
        f"| **new** (body in neither KB nor holdout) | **{len(new)}** |",
        f"| new, but a paraphrase twin of a holdout ticket (cosine >= {TWIN}) | {int(new.holdout_twin.sum())} |",
        f"| new, twin of a KB ticket (cosine >= {TWIN}) | {int((new.kb_sim >= TWIN).sum())} |",
        f"| **new and safe to add** (not a holdout twin) | **{int((~new.holdout_twin).sum())}** |",
        "",
        "## Label agreement where the same body is in the KB",
        "",
        f"{len(ov)} matched rows. Share with the same label in both files:",
        "",
        "| label | agreement |",
        "|---|---|",
        *[f"| {c} | {agree[c] * 100:.1f}% |" for c in LABELS],
        "",
        f"Labels in new rows not seen in the KB: {unknown}.",
        "",
        "## Queue mix",
        "",
        "| queue | kb % | new 20k % |",
        "|---|---|---|",
        *[f"| {q} | {r['kb %']} | {r['new 20k %']} |" for q, r in dist.iterrows()],
        "",
    ]
    REPORT.write_text("\n".join(L), encoding="utf-8", newline="\n")
    print("\n".join(L[6:20]))
    print({c: round(v, 3) for c, v in agree.items()}, unknown)


if __name__ == "__main__":
    main()
